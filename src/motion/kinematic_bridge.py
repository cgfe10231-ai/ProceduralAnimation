# 2. Target Conversion & Ownership Mapping
# =============================================================================

def convert_planned_pose_to_wbc_targets(
    planned: KinematicPlannedPose,
) -> WholeBodyControlTargets:
    """Convert a `KinematicPlannedPose` into standardized `WholeBodyControlTargets`.

    Guarantees:
    - Zero loss of root, pelvis, spine, neck, head, and limb coordinates.
    - Explicit FK/IK arbitration: when `hand_tgt.enabled == False`, arm IK is disabled
      and FK joint rotations in `fk_joint_rotations_deg` take complete control.
    - Explicit foot support lock flag forwarding: `is_locked` is propagated so
      WholeBodyController will not attempt to unlock or overwrite a stance foot.
    """
    targets = WholeBodyControlTargets()

    # Floating base
    targets.root_position = planned.root_position
    targets.root_yaw_deg = planned.root_yaw_deg
    targets.pelvis_location = planned.pelvis_location
    targets.pelvis_rotation_deg = planned.pelvis_rotation_deg

    # Trunk FK
    targets.spine_rotation_deg = planned.spine_rotation_deg
    targets.neck_rotation_deg = planned.neck_rotation_deg
    targets.head_rotation_deg = planned.head_rotation_deg

    # Forward generic FK rotations (arms, shoulders, etc.)
    targets.fk_joint_rotations_deg = dict(planned.fk_joint_rotations_deg)

    # Feet
    targets.foot_L = EndEffectorTarget(
        effector_id="foot_L",
        target_world_xyz=planned.foot_L.world_xyz,
        target_rotation_deg=planned.foot_L.rotation_deg,
        is_locked=planned.foot_L.is_locked,
        enabled=True,
        weight=1.0,
        clamp_reach=planned.foot_L.clamp_reach,
        clamp_ground=planned.foot_L.clamp_ground,
    )
    targets.foot_R = EndEffectorTarget(
        effector_id="foot_R",
        target_world_xyz=planned.foot_R.world_xyz,
        target_rotation_deg=planned.foot_R.rotation_deg,
        is_locked=planned.foot_R.is_locked,
        enabled=True,
        weight=1.0,
        clamp_reach=planned.foot_R.clamp_reach,
        clamp_ground=planned.foot_R.clamp_ground,
    )

    # Hands (IK or FK)
    if planned.hand_L is not None and planned.hand_L.enabled:
        targets.hand_L = EndEffectorTarget(
            effector_id="hand_L",
            target_world_xyz=planned.hand_L.world_xyz,
            target_rotation_deg=planned.hand_L.rotation_deg,
            enabled=True,
            weight=planned.hand_L.weight,
        )
    else:
        # Explicitly disabled hand IK: left in FK mode driven by fk_joint_rotations_deg
        targets.hand_L = EndEffectorTarget(
            effector_id="hand_L",
            target_world_xyz=(0.0, 0.0, 0.0),
            enabled=False,
            weight=0.0,
        )

    if planned.hand_R is not None and planned.hand_R.enabled:
        targets.hand_R = EndEffectorTarget(
            effector_id="hand_R",
            target_world_xyz=planned.hand_R.world_xyz,
            target_rotation_deg=planned.hand_R.rotation_deg,
            enabled=True,
            weight=planned.hand_R.weight,
        )
    else:
        targets.hand_R = EndEffectorTarget(
            effector_id="hand_R",
            target_world_xyz=(0.0, 0.0, 0.0),
            enabled=False,
            weight=0.0,
        )

    return targets


