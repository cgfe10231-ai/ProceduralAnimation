@dataclass
class BridgeExecutionResult:
    """Full execution output produced by `KinematicBridgeExecutor.execute_frame`."""
    success: bool
    frame: int
    wbc_result: WholeBodyControlResult
    motion_state: MotionState
    unmet_constraints: List[UnmetConstraint]
    tracking_errors: Dict[str, float]
    rom_violations: Dict[str, Any]
    com_world: Tuple[float, float, float]
    support_type: str
    inertia_state: Optional[WholeBodyInertiaState] = None
    contact_geometry_errors: Dict[str, GeometricConstraintResult] = field(default_factory=dict)
    multi_contact: Optional[MultiContactState] = None


class KinematicBridgeExecutor:
    """Executes the strict 6-phase single-frame motion pipeline via WholeBodyController."""

    def __init__(
        self,
        armature_obj: bpy.types.Object,
        root_obj: Optional[bpy.types.Object] = None,
        controller: Optional[WholeBodyController] = None,
        kinematics_tracker: Optional[BodyKinematicsTracker] = None,
        inertia_model: Optional[BodyInertiaModel] = None,
        environment: Optional[EnvironmentQuery] = None,
        surfaces: Optional[Sequence[Any]] = None,
        default_fps: float = 24.0,
    ) -> None:
        self.armature_obj = armature_obj
        self.root_obj = root_obj or armature_obj.parent or bpy.data.objects.get("CharacterRoot")
        self.controller = controller or WholeBodyController(armature_obj=self.armature_obj, root_obj=self.root_obj)
        self.kinematics_tracker = kinematics_tracker or BodyKinematicsTracker(
            armature_obj=self.armature_obj,
            root_obj=self.root_obj,
            mass_distribution=self.controller.mass_distribution,
        )
        self.inertia_model = inertia_model or DEFAULT_15_SEGMENT_INERTIA_MODEL
        self.environment = environment or EnvironmentQuery()
        self.surfaces = surfaces
        self.default_fps = float(default_fps)
        self._last_time_sec: Optional[float] = None
        self._last_frame: Optional[int] = None
        self.last_multi_contact: Optional[MultiContactState] = None
        self.last_active_limb_targets: Optional[Dict[str, Dict[str, Any]]] = None

    def reset(self) -> None:
        """Reset internal sequential state tracker and differential kinematics cache."""
        self._last_time_sec = None
        self._last_frame = None
        self.last_multi_contact = None
        self.last_active_limb_targets = None
        if hasattr(self.kinematics_tracker, "reset"):
            self.kinematics_tracker.reset()

    def execute_frame(
        self,
        planned: KinematicPlannedPose,
        keyframe: bool = True,
        enforce_rom_clamping: bool = False,
        dt: Optional[float] = None,
    ) -> BridgeExecutionResult:
        """Execute a single frame according to the official 6-phase pipeline protocol."""
        arm = self.armature_obj
        root = self.root_obj
        frame = planned.frame

        # ---------------------------------------------------------------------
        # Time Step Resolution & Validation
        # ---------------------------------------------------------------------
        if dt is not None:
            if dt <= 0.0:
                raise ValueError(f"Explicit dt={dt} must be strictly positive (> 0.0)")
            effective_dt = float(dt)
        elif planned.dt is not None:
            if planned.dt <= 0.0:
                raise ValueError(f"Planned dt={planned.dt} must be strictly positive (> 0.0)")
            effective_dt = float(planned.dt)
        else:
            if self._last_time_sec is not None:
                calc_dt = planned.time_seconds - self._last_time_sec
                if calc_dt <= 1e-9:
                    raise ValueError(
                        f"Non-positive time step detected: current time_seconds={planned.time_seconds} "
                        f"<= previous time_seconds={self._last_time_sec} (dt={calc_dt})"
                    )
                effective_dt = calc_dt
            else:
                effective_dt = 1.0 / self.default_fps

        # ---------------------------------------------------------------------
        # Phase 1: Planning / Target Packaging
        # ---------------------------------------------------------------------
        wbc_targets = convert_planned_pose_to_wbc_targets(planned)

        # ---------------------------------------------------------------------
        # Phase 2: Contact Coordination & Stance Locking
        # ---------------------------------------------------------------------
        # Stance foot locking is handled via `wbc_targets.foot_L.is_locked` and
        # `wbc_targets.foot_R.is_locked`. WholeBodyController coordinates with
        # `foot_contact.py` so locked feet remain at their world contact points.

        # ---------------------------------------------------------------------
        # Phase 3: WBC Pose Solve (FK & IK Dispatch)
        # ---------------------------------------------------------------------
        wbc_res = self.controller.execute_frame(
            targets=wbc_targets,
            update_scene=True,
            enforce_rom_clamping=enforce_rom_clamping,
        )

        # ---------------------------------------------------------------------
        # Phase 4: Truthful Validation (ROM, Reach, Contacts)
        # ---------------------------------------------------------------------
        unmet = list(wbc_res.unmet_constraints)
        tracking_errors = {k: v.position_error_m for k, v in wbc_res.end_effectors.items() if v.enabled}
        rom_viols = wbc_res.rom_validation.violations

        # ---------------------------------------------------------------------
        # Phase 5: Blender Scene Evaluation & Read-Only Physics Telemetry
        # ---------------------------------------------------------------------
        bpy.context.view_layer.update()

        # Telemetry A: Center of Mass (CoM)
        com_res = compute_whole_body_com(arm, self.controller.mass_distribution, update_scene=False)
        com_world = com_res.com_world

        # Telemetry B: Differential Kinematics
        kin_result = self.kinematics_tracker.sample_and_update(
            time_sec=planned.time_seconds,
            frame=frame,
            dt=effective_dt,
        )

        # Telemetry C: Rigid Link Inertia Tensor & Whole-Body Angular Momentum
        inertia_state = compute_whole_body_inertia(
            armature_obj=arm,
            velocity_state=kin_result.velocity,
            inertia_model=self.inertia_model,
            update_scene=False,
            time_sec=planned.time_seconds,
            frame=frame,
        )

        # Telemetry D: Multi-Limb Contact State & Decoupled Semantics
        surfaces: List[EnvironmentalSurface] = list(self.surfaces) if self.surfaces else []
        active_limb_targets: Dict[str, Dict[str, Any]] = {}

        # Foot contact intent & locking
        for side, ft in [("L", planned.foot_L), ("R", planned.foot_R)]:
            limb_key = f"foot_{side}"
            local_anchor = DEFAULT_LIMB_LOCAL_ANCHORS.get(limb_key, (0.0, 0.015906, -0.068169))
            p_foot = arm.pose.bones.get(f"foot.{side}")

            if ft.is_locked:
                # Query ground support at the evaluated foot sole XY (or planned XY if bone missing)
                if p_foot is not None:
                    foot_mat_world = arm.matrix_world @ p_foot.matrix
                    sole_world_p = foot_mat_world @ Vector(local_anchor)
                    query_x, query_y = sole_world_p.x, sole_world_p.y
                else:
                    query_x, query_y = ft.world_xyz[0], ft.world_xyz[1]

                query_res = self.environment.query_ground_support_at(query_x, query_y)
                if query_res.success:
                    target_pos = query_res.contact_point_world
                    target_normal = query_res.surface_normal_world
                    surf_id = query_res.surface_id if query_res.surface_id not in ("none", "") else ft.surface_id
                    friction_s = getattr(query_res, "friction_coeff", 0.60)
                    friction_d = max(0.0, friction_s - 0.10)

                    # Ensure environmental surface is registered in surfaces list
                    if not any(s.surface_id == surf_id for s in surfaces):
                        surfaces.append(
                            EnvironmentalSurface(
                                surface_id=surf_id,
                                surface_type=query_res.surface_type,
                                center_world=target_pos,
                                normal_world=target_normal,
                                friction_static=friction_s,
                                friction_dynamic=friction_d,
                            )
                        )

                    active_limb_targets[limb_key] = {
                        "surface_id": surf_id,
                        "target_world": target_pos,
                        "normal_world": target_normal,
                        "contact_type": ft.contact_type,
                        "lifecycle": ContactLifecycle.ESTABLISHED,
                        "local_anchor": local_anchor,
                        "friction_static": friction_s,
                        "friction_dynamic": friction_d,
                    }
                else:
                    # Query failed: no valid mesh support found (never fake Z=0.0m ground)
                    active_limb_targets[limb_key] = {
                        "surface_id": "none",
                        "target_world": query_res.contact_point_world,
                        "normal_world": query_res.surface_normal_world,
                        "contact_type": ContactType.FREE,
                        "lifecycle": ContactLifecycle.BROKEN,
                        "local_anchor": local_anchor,
                        "error_reason": query_res.error_reason,
                    }
            elif ft.contact_intent:
                active_limb_targets[limb_key] = {
                    "surface_id": ft.surface_id,
                    "target_world": ft.world_xyz,
                    "normal_world": ft.normal_world,
                    "contact_type": ContactType.FREE,
                    "lifecycle": ContactLifecycle.RELEASED,
                    "local_anchor": local_anchor,
                }
            else:
                active_limb_targets[limb_key] = {
                    "surface_id": "free",
                    "target_world": ft.world_xyz,
                    "normal_world": (0.0, 0.0, 1.0),
                    "contact_type": ContactType.FREE,
                    "lifecycle": ContactLifecycle.RELEASED,
                    "local_anchor": local_anchor,
                }

        # Ensure at least a fallback analytical ground surface exists in surfaces list if empty
        if not surfaces:
            default_gz = self.environment.ground_z if hasattr(self.environment, "ground_z") else 0.0
            surfaces.append(
                EnvironmentalSurface(
                    surface_id="ground",
                    surface_type="ground",
                    center_world=(0.0, 0.0, default_gz),
                    normal_world=(0.0, 0.0, 1.0),
                )
            )

        # Hand contact intent & locking: clean separation between IK enablement and contact intent
        for side, ht in [("L", planned.hand_L), ("R", planned.hand_R)]:
            limb_key = f"hand_{side}"
            if ht is not None and ht.enabled:
                if ht.is_locked:
                    c_type = ht.contact_type if ht.contact_type != ContactType.FREE else ContactType.UNILATERAL
                    active_limb_targets[limb_key] = {
                        "surface_id": ht.surface_id or f"{limb_key}_target",
                        "target_world": ht.world_xyz,
                        "normal_world": ht.normal_world,
                        "contact_type": c_type,
                        "lifecycle": ContactLifecycle.ESTABLISHED,
                    }
                elif ht.contact_intent:
                    # Intends contact with an environmental surface
                    p_hand = arm.pose.bones.get(f"hand.{side}")
                    actual_hand_p = (arm.matrix_world @ p_hand.head) if p_hand else Vector(ht.world_xyz)
                    dist = (actual_hand_p - Vector(ht.world_xyz)).length
                    c_type = ht.contact_type if ht.contact_type != ContactType.FREE else ContactType.UNILATERAL
                    active_limb_targets[limb_key] = {
                        "surface_id": ht.surface_id or f"{limb_key}_target",
                        "target_world": ht.world_xyz,
                        "normal_world": ht.normal_world,
                        "contact_type": c_type,
                        "lifecycle": ContactLifecycle.ESTABLISHED if dist <= 0.015 else ContactLifecycle.TOUCHDOWN,
                    }
                else:
                    # Pure reaching / waving IK: zero contact intent!
                    active_limb_targets[limb_key] = {
                        "surface_id": "free",
                        "target_world": ht.world_xyz,
                        "normal_world": (0.0, 0.0, 1.0),
                        "contact_type": ContactType.FREE,
                        "lifecycle": ContactLifecycle.RELEASED,
                    }
            else:
                active_limb_targets[limb_key] = {
                    "surface_id": "free",
                    "target_world": (0.0, 0.0, 0.0),
                    "normal_world": (0.0, 0.0, 1.0),
                    "contact_type": ContactType.FREE,
                    "lifecycle": ContactLifecycle.RELEASED,
                }

        multi_contact = evaluate_limb_contacts_from_armature(
            armature_obj=arm,
            surfaces=surfaces,
            active_limb_targets=active_limb_targets,
        )

        # Contact Geometric Compliance Checking
        contact_geom_errors: Dict[str, GeometricConstraintResult] = {}
        actual_positions: Dict[str, Tuple[float, float, float]] = {}
        for side in ("L", "R"):
            limb_key = f"foot_{side}"
            p_foot = arm.pose.bones.get(f"foot.{side}")
            if p_foot is not None:
                foot_mat_world = arm.matrix_world @ p_foot.matrix
                anchor_local = active_limb_targets.get(limb_key, {}).get("local_anchor", DEFAULT_LIMB_LOCAL_ANCHORS.get(limb_key, (0.0, 0.0, 0.0)))
                sole_world = foot_mat_world @ Vector(anchor_local)
                actual_positions[limb_key] = (sole_world.x, sole_world.y, sole_world.z)
            else:
                p_shin = arm.pose.bones.get(f"shin.{side}")
                if p_shin is not None:
                    ankle_world = arm.matrix_world @ p_shin.tail
                    actual_positions[limb_key] = (ankle_world.x, ankle_world.y, ankle_world.z - ANKLE_REST_Z)
            p_hand = arm.pose.bones.get(f"hand.{side}")
            if p_hand is not None:
                wrist_world = arm.matrix_world @ p_hand.head
                actual_positions[f"hand_{side}"] = (wrist_world.x, wrist_world.y, wrist_world.z)

        geom_compliance = multi_contact.check_all_contacts(actual_positions)
        for limb, geom_res in geom_compliance.items():
            rec = multi_contact.contacts.get(limb)
            if rec is not None and rec.is_active and not geom_res.is_valid:
                contact_geom_errors[limb] = geom_res
                unmet.append(
                    UnmetConstraint(
                        category="CONTACT_GEOMETRY",
                        target_name=limb,
                        description=geom_res.violation_reason or f"Geometric contact violation on {limb}",
                        error_amount=geom_res.total_position_error_m,
                        details={
                            "gap_m": geom_res.distance_normal_m,
                            "slip_m": geom_res.tangential_slip_m,
                            "penetration_m": geom_res.penetration_depth_m,
                        },
                    )
                )
            elif rec is not None and rec.lifecycle == ContactLifecycle.BROKEN:
                reason = rec.metadata.get("error_reason") or "No valid ground support surface intersected"
                broken_res = GeometricConstraintResult(
                    is_valid=False,
                    total_position_error_m=float("inf"),
                    distance_normal_m=float("inf"),
                    penetration_depth_m=0.0,
                    tangential_slip_m=0.0,
                    violation_reason=f"NO_SUPPORT_SURFACE: {reason}",
                )
                contact_geom_errors[limb] = broken_res
                unmet.append(
                    UnmetConstraint(
                        category="CONTACT_GEOMETRY",
                        target_name=limb,
                        description=f"Contact geometric constraint violated: {broken_res.violation_reason}",
                        error_amount=1.0,
                        details={"error": reason},
                    )
                )

        # ---------------------------------------------------------------------
        # Phase 6: State Commit & Keyframing
        # ---------------------------------------------------------------------
        if keyframe:
            # Keyframe root object
            if root is not None:
                root.keyframe_insert("location", frame=frame)
                root.keyframe_insert("rotation_euler", frame=frame)

            # Keyframe armature pose bones
            for pb in arm.pose.bones:
                pb.keyframe_insert("location", frame=frame)
                pb.keyframe_insert("rotation_euler", frame=frame)

            # Keyframe IK control empties
            for name in ("FootIK.L", "FootIK.R", "KneePole.L", "KneePole.R", "HandIK.L", "HandIK.R", "ElbowPole.L", "ElbowPole.R"):
                obj = bpy.data.objects.get(name)
                if obj is not None:
                    obj.keyframe_insert("location", frame=frame)
                    obj.keyframe_insert("rotation_euler", frame=frame)

        # Assemble legacy & contact states
        contact_states: Dict[str, ContactPointState] = {}
        for side in ("L", "R"):
            limb_key = f"foot_{side.lower()}"
            is_locked = (planned.foot_L.is_locked if side == "L" else planned.foot_R.is_locked)
            eff_fb = wbc_res.end_effectors.get(f"foot_{side}")
            contact_states[limb_key] = ContactPointState(
                limb=limb_key,
                phase="stance" if is_locked else "swing",
                is_locked=is_locked,
                contact_world_xyz=eff_fb.actual_world_xyz if eff_fb else (0.0, 0.0, 0.0),
                current_world_xyz=eff_fb.actual_world_xyz if eff_fb else (0.0, 0.0, 0.0),
                drift_m=eff_fb.position_error_m if eff_fb else 0.0,
                hip_to_target_dist=eff_fb.reach_distance_m if eff_fb else 0.0,
                is_reachable=eff_fb.is_reachable if eff_fb else True,
                strictly_in_reach=eff_fb.strictly_in_reach if eff_fb else True,
            )

        root_world = root.location.to_tuple() if root is not None else (0.0, 0.0, 0.0)
        fx, fy, _ = forward_unit_vector_from_yaw(planned.root_yaw_deg)
        planned_vel = (fx * planned.speed_mps, fy * planned.speed_mps, 0.0)
        planned_acc = (fx * planned.accel_mps2, fy * planned.accel_mps2, 0.0)
        motion_state = MotionState(
            frame=frame,
            time_sec=planned.time_seconds,
            position=root_world,
            orientation_deg=(0.0, 0.0, planned.root_yaw_deg),
            velocity=planned_vel,
            acceleration=planned_acc,
            mode=planned.motion_mode,
            gait_phase=planned.gait_phase,
            contacts=contact_states,
            is_airborne=planned.is_flight,
            params={
                "step_index": planned.active_step_index,
                "com_world": com_world,
                "support_type": multi_contact.support_type.value,
                "tracking_errors_m": tracking_errors,
                "has_rom_violation": wbc_res.has_rom_violation,
                "dt_seconds": effective_dt,
                "planned_linear_velocity": planned_vel,
            },
        )

        motion_state = enrich_motion_state_with_kinematics(motion_state, kin_result)
        motion_state = enrich_motion_state_with_contacts(motion_state, multi_contact)
        motion_state = enrich_motion_state_with_inertia(motion_state, inertia_state)

        # Update internal temporal progression
        self._last_time_sec = planned.time_seconds
        self._last_frame = frame
        self.last_multi_contact = multi_contact
        self.last_active_limb_targets = active_limb_targets

        overall_success = wbc_res.success and (len(unmet) == 0)

        return BridgeExecutionResult(
            success=overall_success,
            frame=frame,
            wbc_result=wbc_res,
            motion_state=motion_state,
            unmet_constraints=unmet,
            tracking_errors=tracking_errors,
            rom_violations=rom_viols,
            com_world=com_world,
            support_type=multi_contact.support_type.value,
            inertia_state=inertia_state,
            contact_geometry_errors=contact_geom_errors,
            multi_contact=multi_contact,
        )
