@dataclass
class PlannedFootTarget:
    """Kinematic target for a single foot at a discrete time step."""
    world_xyz: Tuple[float, float, float]
    is_locked: bool = False
    rotation_deg: Tuple[float, float, float] = (0.0, 0.0, 0.0)
    clamp_reach: bool = True
    clamp_ground: bool = True

    # Contact semantics: distinct from IK target positioning
    contact_intent: bool = True  # In locomotion actions, foot targets a surface (ground)
    surface_id: str = "ground"
    contact_type: ContactType = ContactType.UNILATERAL
    normal_world: Tuple[float, float, float] = (0.0, 0.0, 1.0)


@dataclass
class PlannedHandTarget:
    """Kinematic target for a single hand at a discrete time step."""
    world_xyz: Tuple[float, float, float]
    rotation_deg: Optional[Tuple[float, float, float]] = None
    enabled: bool = False  # False = hand in FK mode; True = hand in IK mode
    weight: float = 1.0

    # Explicit contact intent and locking fields (decoupling IK from contact)
    contact_intent: bool = False  # True only if action specifically intends surface contact
    is_locked: bool = False       # True if hand contact is established & locked in world space
    surface_id: Optional[str] = None  # Targeted surface ID (e.g. "vault_box", "bar", "wall")
    contact_type: ContactType = ContactType.FREE  # UNILATERAL, GRASP, or FREE
    normal_world: Tuple[float, float, float] = (0.0, 0.0, 1.0)


@dataclass
class KinematicPlannedPose:
    """Lossless container of kinematic targets generated by a MotionAction."""
    frame: int
    time_seconds: float
    root_position: Tuple[float, float, float]
    root_yaw_deg: float = 0.0
    speed_mps: float = 0.0
    accel_mps2: float = 0.0
    motion_mode: MotionMode = MotionMode.WALK
    dt: Optional[float] = None  # Optional explicit frame duration in seconds

    # Floating base & axial FK posture
    pelvis_location: Tuple[float, float, float] = (0.0, 0.0, 0.0)
    pelvis_rotation_deg: Tuple[float, float, float] = (0.0, 0.0, 0.0)
    spine_rotation_deg: Tuple[float, float, float] = (0.0, 0.0, 0.0)
    neck_rotation_deg: Tuple[float, float, float] = (0.0, 0.0, 0.0)
    head_rotation_deg: Tuple[float, float, float] = (0.0, 0.0, 0.0)

    # Foot kinematics
    foot_L: PlannedFootTarget = field(default_factory=lambda: PlannedFootTarget((0.0, 0.0, ANKLE_REST_Z)))
    foot_R: PlannedFootTarget = field(default_factory=lambda: PlannedFootTarget((0.0, 0.0, ANKLE_REST_Z)))

    # Hand kinematics (IK mode or FK mode)
    hand_L: Optional[PlannedHandTarget] = None
    hand_R: Optional[PlannedHandTarget] = None

    # Generic FK joint rotations (e.g. arm swinging in walk/run: upper_arm, forearm, hand)
    fk_joint_rotations_deg: Dict[str, Tuple[float, float, float]] = field(default_factory=dict)

    # Step metadata for analysis
    active_step_index: int = -1
    gait_phase: float = 0.0
    is_flight: bool = False


