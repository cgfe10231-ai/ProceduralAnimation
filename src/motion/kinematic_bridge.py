@dataclass
class BridgeExecutionResult:
    """Full execution output produced by `KinematicBridgeExecutor.execute_frame`."""
    success: bool
    frame: int
    wbc_result: WholeBodyControlResult
    motion_state: MotionState
    unmet_constraints: List[UnmetConstraint]
    tracking_errors: Dict[str, float]
    rom_violations: Dict[str, Any]
    com_world: Tuple[float, float, float]
    support_type: str
    inertia_state: Optional[WholeBodyInertiaState] = None
    contact_geometry_errors: Dict[str, GeometricConstraintResult] = field(default_factory=dict)
    multi_contact: Optional[MultiContactState] = None


class KinematicBridgeExecutor:
    """Executes the strict 6-phase single-frame motion pipeline via WholeBodyController."""

    def __init__(
        self,
        armature_obj: bpy.types.Object,
        root_obj: Optional[bpy.types.Object] = None,
        controller: Optional[WholeBodyController] = None,
        kinematics_tracker: Optional[BodyKinematicsTracker] = None,
        inertia_model: Optional[BodyInertiaModel] = None,
        environment: Optional[EnvironmentQuery] = None,
        surfaces: Optional[Sequence[Any]] = None,
        default_fps: float = 24.0,
    ) -> None:
        self.armature_obj = armature_obj
        self.root_obj = root_obj or armature_obj.parent or bpy.data.objects.get("CharacterRoot")
        self.controller = controller or WholeBodyController(armature_obj=self.armature_obj, root_obj=self.root_obj)
        self.kinematics_tracker = kinematics_tracker or BodyKinematicsTracker(
            armature_obj=self.armature_obj,
            root_obj=self.root_obj,
            mass_distribution=self.controller.mass_distribution,
        )
        self.inertia_model = inertia_model or DEFAULT_15_SEGMENT_INERTIA_MODEL
        self.environment = environment or EnvironmentQuery()
        self.surfaces = surfaces
        self.default_fps = float(default_fps)
        self._last_time_sec: Optional[float] = None
        self._last_frame: Optional[int] = None
        self.last_multi_contact: Optional[MultiContactState] = None
        self.last_active_limb_targets: Optional[Dict[str, Dict[str, Any]]] = None

    def reset(self) -> None:
        """Reset internal sequential state tracker and differential kinematics cache."""
        self._last_time_sec = None
        self._last_frame = None
        self.last_multi_contact = None
        self.last_active_limb_targets = None
        if hasattr(self.kinematics_tracker, "reset"):
            self.kinematics_tracker.reset()

    def execute_frame(
        self,
        planned: KinematicPlannedPose,
        keyframe: bool = True,
        enforce_rom_clamping: bool = False,
        dt: Optional[float] = None,
    ) -> BridgeExecutionResult:
        """Execute a single frame according to the official 6-phase pipeline protocol."""
        arm = self.armature_obj
        root = self.root_obj
        frame = planned.frame

        # ---------------------------------------------------------------------
        # Time Step Resolution & Validation
        # ---------------------------------------------------------------------
        # [INTRODUCED 2026-11-27T21:05:10+08:00]
        # FUNCTION: KinematicBridgeExecutor.execute_frame.timing_admission_validation
        # PURPOSE: Reject invalid frame/time ordering before WBC and enforce a single unified finite and > 1e-9s validity gate on the final resolved effective_dt across all timestep sources.
        # REASON: TASK 12-B BUG-04
        if isinstance(frame, bool) or not isinstance(frame, int):
            raise ValueError(f"Frame number must be an integer, got {frame!r}")

        time_sec = planned.time_seconds
        if isinstance(time_sec, bool) or not isinstance(time_sec, (int, float)) or not math.isfinite(float(time_sec)):
            raise ValueError(f"Planned time_seconds={time_sec!r} must be a finite number")
        time_sec_f = float(time_sec)

        if self._last_frame is not None and frame <= self._last_frame:
            raise ValueError(
                f"Non-increasing frame number detected: current frame={frame} "
                f"<= previous committed frame={self._last_frame}"
            )
        if self._last_time_sec is not None and (time_sec_f <= self._last_time_sec or (time_sec_f - self._last_time_sec) <= 1e-9):
            raise ValueError(
                f"Non-increasing time step detected: current time_seconds={time_sec_f} "
                f"<= previous committed time_seconds={self._last_time_sec}"
            )

        if dt is not None:
            dt_source = "explicit dt"
            raw_dt = dt
        elif planned.dt is not None:
            dt_source = "planned.dt"
            raw_dt = planned.dt
        elif self._last_time_sec is not None:
            dt_source = "timestamp delta"
            raw_dt = time_sec_f - self._last_time_sec
        else:
            dt_source = f"default_fps={self.default_fps!r}"
            if isinstance(self.default_fps, bool) or not isinstance(self.default_fps, (int, float)):
                raise ValueError(f"Bridge default_fps={self.default_fps!r} must be numeric")
            fps_val = float(self.default_fps)
            raw_dt = (1.0 / fps_val) if fps_val != 0.0 else 0.0

        if isinstance(raw_dt, bool) or not isinstance(raw_dt, (int, float)):
            raise ValueError(f"Resolved timestep from {dt_source} must be numeric, got {raw_dt!r}")
        effective_dt = float(raw_dt)
        if not math.isfinite(effective_dt) or effective_dt <= 1e-9:
            raise ValueError(
                f"Resolved effective_dt={effective_dt!r} (from {dt_source}) must be finite and strictly greater than 1e-9s"
            )

        # [INTRODUCED 2026-11-27T21:22:00+08:00]
        # FUNCTION: KinematicBridgeExecutor.execute_frame.mass_distribution_consistency_gate
        # PURPOSE: Reject physically inconsistent BodyMassDistribution parameters across controller, kinematics_tracker, and inertia_model before WBC pose solving without relying on model_name or creating a global registry.
        # REASON: TASK 12-C BUG-02
        mass_dists = (
            ("controller", getattr(self.controller, "mass_distribution", None)),
            ("kinematics_tracker", getattr(self.kinematics_tracker, "mass_distribution", None)),
            ("inertia_model", getattr(self.inertia_model, "mass_distribution", None)),
        )
        ref_owner, ref_dist = mass_dists[0]
        if ref_dist is None or not hasattr(ref_dist, "total_mass_kg") or not hasattr(ref_dist, "segments"):
            raise ValueError(f"Missing valid mass_distribution on {ref_owner}")
        ref_segments = {seg.segment_id: seg for seg in ref_dist.segments}
        for owner_name, dist in mass_dists[1:]:
            if dist is ref_dist:
                continue
            if dist is None or not hasattr(dist, "total_mass_kg") or not hasattr(dist, "segments"):
                raise ValueError(f"Missing valid mass_distribution on {owner_name}")
            if not math.isclose(float(dist.total_mass_kg), float(ref_dist.total_mass_kg), rel_tol=1e-9, abs_tol=1e-9):
                raise ValueError(
                    f"Mass distribution total_mass_kg mismatch between {ref_owner} "
                    f"({ref_dist.total_mass_kg}) and {owner_name} ({dist.total_mass_kg})"
                )
            cand_segments = {seg.segment_id: seg for seg in dist.segments}
            if len(cand_segments) != len(dist.segments) or set(cand_segments.keys()) != set(ref_segments.keys()):
                raise ValueError(
                    f"Mass distribution segment mapping mismatch between {ref_owner} and {owner_name}"
                )
            for seg_id, ref_seg in ref_segments.items():
                cand_seg = cand_segments[seg_id]
                if cand_seg.bone_name != ref_seg.bone_name:
                    raise ValueError(
                        f"Mass distribution bone_name mismatch for segment '{seg_id}' between "
                        f"{ref_owner} ({ref_seg.bone_name!r}) and {owner_name} ({cand_seg.bone_name!r})"
                    )
                if not (
                    math.isclose(float(cand_seg.mass_ratio), float(ref_seg.mass_ratio), rel_tol=1e-9, abs_tol=1e-9)
                    and math.isclose(float(cand_seg.nominal_length), float(ref_seg.nominal_length), rel_tol=1e-9, abs_tol=1e-9)
                    and math.isclose(float(cand_seg.local_com_fraction), float(ref_seg.local_com_fraction), rel_tol=1e-9, abs_tol=1e-9)
                    and len(cand_seg.local_com_offset) == 3
                    and len(ref_seg.local_com_offset) == 3
                    and all(
                        math.isclose(float(a), float(b), rel_tol=1e-9, abs_tol=1e-9)
                        for a, b in zip(cand_seg.local_com_offset, ref_seg.local_com_offset)
                    )
                ):
                    raise ValueError(
                        f"Mass distribution physical parameter mismatch for segment '{seg_id}' between "
                        f"{ref_owner} and {owner_name}"
                    )

        # ---------------------------------------------------------------------
        # Phase 1: Planning / Target Packaging
        # ---------------------------------------------------------------------
        wbc_targets = convert_planned_pose_to_wbc_targets(planned)

        # ---------------------------------------------------------------------
        # Phase 2: Contact Coordination & Stance Locking
        # ---------------------------------------------------------------------
        # Stance foot locking is handled via `wbc_targets.foot_L.is_locked` and
        # `wbc_targets.foot_R.is_locked`. WholeBodyController coordinates with
        # `foot_contact.py` so locked feet remain at their world contact points.

        # ---------------------------------------------------------------------
        # Phase 3: WBC Pose Solve (FK & IK Dispatch)
        # ---------------------------------------------------------------------
        wbc_res = self.controller.execute_frame(
            targets=wbc_targets,
            update_scene=True,
            enforce_rom_clamping=enforce_rom_clamping,
        )

        # ---------------------------------------------------------------------
        # Phase 4: Truthful Validation (ROM, Reach, Contacts)
        # ---------------------------------------------------------------------
        unmet = list(wbc_res.unmet_constraints)
        tracking_errors = {k: v.position_error_m for k, v in wbc_res.end_effectors.items() if v.enabled}
        rom_viols = wbc_res.rom_validation.violations

        # ---------------------------------------------------------------------
        # Phase 5: Read-Only Physics Telemetry
        # ---------------------------------------------------------------------
        bpy.context.view_layer.update()

        # Telemetry A: Authoritative Whole-Body CoM from WBC result
        com_res = wbc_res.com_result
        com_world = com_res.com_world

        # Telemetry B: Multi-Limb Contact State & Geometric Compliance Validation
        surfaces: List[EnvironmentalSurface] = list(self.surfaces) if self.surfaces else []
        active_limb_targets: Dict[str, Dict[str, Any]] = {}

        # Foot contact intent & locking
        for side, ft in [("L", planned.foot_L), ("R", planned.foot_R)]:
            limb_key = f"foot_{side}"
            local_anchor = DEFAULT_LIMB_LOCAL_ANCHORS.get(limb_key, (0.0, 0.015906, -0.068169))
            p_foot = arm.pose.bones.get(f"foot.{side}")

            if ft.is_locked:
                # Query ground support at the evaluated foot sole XY (or planned XY if bone missing)
                if p_foot is not None:
                    foot_mat_world = arm.matrix_world @ p_foot.matrix
                    sole_world_p = foot_mat_world @ Vector(local_anchor)
                    query_x, query_y = sole_world_p.x, sole_world_p.y
                else:
                    query_x, query_y = ft.world_xyz[0], ft.world_xyz[1]

                query_res = self.environment.query_ground_support_at(query_x, query_y)
                if query_res.success and query_res.allows_regular_support:
                    target_pos = query_res.contact_point_world
                    target_normal = query_res.surface_normal_world
                    surf_id = query_res.surface_id if query_res.surface_id not in ("none", "") else ft.surface_id
                    friction_s = getattr(query_res, "friction_coeff", 0.60)
                    friction_d = max(0.0, friction_s - 0.10)

                    # Ensure environmental surface is registered in surfaces list
                    if not any(s.surface_id == surf_id for s in surfaces):
                        surfaces.append(
                            EnvironmentalSurface(
                                surface_id=surf_id,
                                surface_type=query_res.surface_type,
                                center_world=target_pos,
                                normal_world=target_normal,
                                friction_static=friction_s,
                                friction_dynamic=friction_d,
                            )
                        )

                    active_limb_targets[limb_key] = {
                        "surface_id": surf_id,
                        "target_world": target_pos,
                        "normal_world": target_normal,
                        "contact_type": ft.contact_type,
                        "lifecycle": ContactLifecycle.ESTABLISHED,
                        "local_anchor": local_anchor,
                        "friction_static": friction_s,
                        "friction_dynamic": friction_d,
                    }
                else:
                    # Query failed or surface does not allow regular support (never fake Z=0.0m ground)
                    err_reason = query_res.error_reason or (
                        f"NON_SUPPORT_SURFACE: surface '{query_res.surface_id}' does not allow regular support"
                        if not query_res.allows_regular_support
                        else "No valid ground support surface intersected"
                    )
                    active_limb_targets[limb_key] = {
                        "surface_id": "none",
                        "target_world": query_res.contact_point_world,
                        "normal_world": query_res.surface_normal_world,
                        "contact_type": ContactType.FREE,
                        "lifecycle": ContactLifecycle.BROKEN,
                        "local_anchor": local_anchor,
                        "error_reason": err_reason,
                    }
            elif ft.contact_intent:
                active_limb_targets[limb_key] = {
                    "surface_id": ft.surface_id,
                    "target_world": ft.world_xyz,
                    "normal_world": ft.normal_world,
                    "contact_type": ContactType.FREE,
                    "lifecycle": ContactLifecycle.RELEASED,
                    "local_anchor": local_anchor,
                }
            else:
                active_limb_targets[limb_key] = {
                    "surface_id": "free",
                    "target_world": ft.world_xyz,
                    "normal_world": (0.0, 0.0, 1.0),
                    "contact_type": ContactType.FREE,
                    "lifecycle": ContactLifecycle.RELEASED,
                    "local_anchor": local_anchor,
                }

        # Ensure at least a fallback analytical ground surface exists in surfaces list if empty
        if not surfaces:
            default_gz = self.environment.ground_z if hasattr(self.environment, "ground_z") else 0.0
            surfaces.append(
                EnvironmentalSurface(
                    surface_id="ground",
                    surface_type="ground",
                    center_world=(0.0, 0.0, default_gz),
                    normal_world=(0.0, 0.0, 1.0),
                )
            )

        # Hand contact intent & locking: clean separation between IK enablement and contact intent
        for side, ht in [("L", planned.hand_L), ("R", planned.hand_R)]:
            limb_key = f"hand_{side}"
            if ht is not None and ht.enabled:
                if ht.is_locked:
                    c_type = ht.contact_type if ht.contact_type != ContactType.FREE else ContactType.UNILATERAL
                    active_limb_targets[limb_key] = {
                        "surface_id": ht.surface_id or f"{limb_key}_target",
                        "target_world": ht.world_xyz,
                        "normal_world": ht.normal_world,
                        "contact_type": c_type,
                        "lifecycle": ContactLifecycle.ESTABLISHED,
                    }
                elif ht.contact_intent:
                    # Intends contact with an environmental surface
                    p_hand = arm.pose.bones.get(f"hand.{side}")
                    actual_hand_p = (arm.matrix_world @ p_hand.head) if p_hand else Vector(ht.world_xyz)
                    dist = (actual_hand_p - Vector(ht.world_xyz)).length
                    c_type = ht.contact_type if ht.contact_type != ContactType.FREE else ContactType.UNILATERAL
                    active_limb_targets[limb_key] = {
                        "surface_id": ht.surface_id or f"{limb_key}_target",
                        "target_world": ht.world_xyz,
                        "normal_world": ht.normal_world,
                        "contact_type": c_type,
                        "lifecycle": ContactLifecycle.ESTABLISHED if dist <= 0.015 else ContactLifecycle.CANDIDATE,
                    }
                else:
                    # Pure reaching / waving IK: zero contact intent!
                    active_limb_targets[limb_key] = {
                        "surface_id": "free",
                        "target_world": ht.world_xyz,
                        "normal_world": (0.0, 0.0, 1.0),
                        "contact_type": ContactType.FREE,
                        "lifecycle": ContactLifecycle.RELEASED,
                    }
            else:
                active_limb_targets[limb_key] = {
                    "surface_id": "free",
                    "target_world": (0.0, 0.0, 0.0),
                    "normal_world": (0.0, 0.0, 1.0),
                    "contact_type": ContactType.FREE,
                    "lifecycle": ContactLifecycle.RELEASED,
                }

        multi_contact = evaluate_limb_contacts_from_armature(
            armature_obj=arm,
            surfaces=surfaces,
            active_limb_targets=active_limb_targets,
        )

        # Contact Geometric Compliance Checking
        contact_geom_errors: Dict[str, GeometricConstraintResult] = {}
        actual_positions: Dict[str, Tuple[float, float, float]] = {}
        for side in ("L", "R"):
            limb_key = f"foot_{side}"
            p_foot = arm.pose.bones.get(f"foot.{side}")
            if p_foot is not None:
                foot_mat_world = arm.matrix_world @ p_foot.matrix
                anchor_local = active_limb_targets.get(limb_key, {}).get("local_anchor", DEFAULT_LIMB_LOCAL_ANCHORS.get(limb_key, (0.0, 0.0, 0.0)))
                sole_world = foot_mat_world @ Vector(anchor_local)
                actual_positions[limb_key] = (sole_world.x, sole_world.y, sole_world.z)
            else:
                p_shin = arm.pose.bones.get(f"shin.{side}")
                if p_shin is not None:
                    ankle_world = arm.matrix_world @ p_shin.tail
                    actual_positions[limb_key] = (ankle_world.x, ankle_world.y, ankle_world.z - ANKLE_REST_Z)
            p_hand = arm.pose.bones.get(f"hand.{side}")
            if p_hand is not None:
                wrist_world = arm.matrix_world @ p_hand.head
                actual_positions[f"hand_{side}"] = (wrist_world.x, wrist_world.y, wrist_world.z)

        geom_compliance = multi_contact.check_all_contacts(actual_positions)
        for limb, geom_res in geom_compliance.items():
            rec = multi_contact.contacts.get(limb)
            if rec is not None and rec.is_lifecycle_active and not geom_res.is_valid:
                contact_geom_errors[limb] = geom_res
                unmet.append(
                    UnmetConstraint(
                        category="CONTACT_GEOMETRY",
                        target_name=limb,
                        description=geom_res.violation_reason or f"Geometric contact violation on {limb}",
                        error_amount=geom_res.total_position_error_m,
                        details={
                            "gap_m": geom_res.distance_normal_m,
                            "slip_m": geom_res.tangential_slip_m,
                            "penetration_m": geom_res.penetration_depth_m,
                        },
                    )
                )
            elif rec is not None and rec.lifecycle == ContactLifecycle.BROKEN:
                reason = (
                    active_limb_targets.get(limb, {}).get("error_reason")
                    or rec.metadata.get("error_reason")
                    or "No valid ground support surface intersected"
                )
                broken_res = GeometricConstraintResult(
                    is_valid=False,
                    total_position_error_m=float("inf"),
                    distance_normal_m=float("inf"),
                    penetration_depth_m=0.0,
                    tangential_slip_m=0.0,
                    violation_reason=f"NO_SUPPORT_SURFACE: {reason}",
                )
                contact_geom_errors[limb] = broken_res
                unmet.append(
                    UnmetConstraint(
                        category="CONTACT_GEOMETRY",
                        target_name=limb,
                        description=f"Contact geometric constraint violated: {broken_res.violation_reason}",
                        error_amount=1.0,
                        details={"error": reason},
                    )
                )

        # [INTRODUCED 2026-11-27T21:22:20+08:00]
        # FUNCTION: KinematicBridgeExecutor.execute_frame.effective_contact_and_com_telemetry
        # PURPOSE: Derive effective contact booleans from MultiContactState.effective_contacts after ContactModel validation and forward them together with authoritative wbc_res.com_result into BodyKinematicsTracker and BodyInertia without duplicate CoM computation or overwritten contact_states loops.
        # REASON: TASK 12-C BUG-02, BUG-03 & BUG-04
        effective_contacts = multi_contact.effective_contacts
        contacts_override = {
            limb_key: (limb_key in effective_contacts)
            for limb_key in ("foot_L", "foot_R", "hand_L", "hand_R")
        }

        # Telemetry C: Differential Kinematics (non-publishing until final frame commit)
        kin_result = self.kinematics_tracker.sample_and_update(
            time_sec=time_sec_f,
            frame=frame,
            dt=effective_dt,
            commit=False,
            com_result=com_res,
            contacts_override=contacts_override,
        )

        # Telemetry D: Rigid Link Inertia Tensor & Whole-Body Angular Momentum
        inertia_state = compute_whole_body_inertia(
            armature_obj=arm,
            velocity_state=kin_result.velocity,
            inertia_model=self.inertia_model,
            update_scene=False,
            time_sec=time_sec_f,
            frame=frame,
            com_result=com_res,
        )

        # ---------------------------------------------------------------------
        # Phase 6: MotionState Assembly, Gated Keyframing & State Commit
        # ---------------------------------------------------------------------
        root_world = root.location.to_tuple() if root is not None else (0.0, 0.0, 0.0)
        fx, fy, _ = forward_unit_vector_from_yaw(planned.root_yaw_deg)
        planned_vel = (fx * planned.speed_mps, fy * planned.speed_mps, 0.0)
        planned_acc = (fx * planned.accel_mps2, fy * planned.accel_mps2, 0.0)
        motion_state = MotionState(
            frame=frame,
            time_sec=time_sec_f,
            position=root_world,
            orientation_deg=(0.0, 0.0, planned.root_yaw_deg),
            velocity=planned_vel,
            acceleration=planned_acc,
            mode=planned.motion_mode,
            gait_phase=planned.gait_phase,
            is_airborne=planned.is_flight,
            params={
                "step_index": planned.active_step_index,
                "com_world": com_world,
                "support_type": multi_contact.support_type.value,
                "tracking_errors_m": tracking_errors,
                "has_rom_violation": wbc_res.has_rom_violation,
                "dt_seconds": effective_dt,
                "planned_linear_velocity": planned_vel,
            },
        )

        motion_state = enrich_motion_state_with_kinematics(motion_state, kin_result)
        motion_state = enrich_motion_state_with_contacts(motion_state, multi_contact)
        motion_state = enrich_motion_state_with_inertia(motion_state, inertia_state)

        overall_success = wbc_res.success and (len(unmet) == 0)

        execution_result = BridgeExecutionResult(
            success=overall_success,
            frame=frame,
            wbc_result=wbc_res,
            motion_state=motion_state,
            unmet_constraints=unmet,
            tracking_errors=tracking_errors,
            rom_violations=rom_viols,
            com_world=com_world,
            support_type=multi_contact.support_type.value,
            inertia_state=inertia_state,
            contact_geometry_errors=contact_geom_errors,
            multi_contact=multi_contact,
        )

        # [INTRODUCED 2026-11-27T20:57:40+08:00]
        # FUNCTION: KinematicBridgeExecutor.execute_frame.gated_commit_boundary
        # PURPOSE: Execute Blender keyframing and formally commit BodyKinematicsTracker and Bridge cross-frame state (_last_time_sec, _last_frame, last_multi_contact, last_active_limb_targets) strictly when overall_success=True, reusing precomputed kin_result without re-running differential kinematics.
        # REASON: TASK 12-B BUG-01 & BUG-02
        if overall_success:
            if keyframe:
                # [INTRODUCED 2026-11-27T21:05:30+08:00]
                # FUNCTION: KinematicBridgeExecutor.execute_frame.keyframe_return_checks
                # PURPOSE: Enforce strict return-value checks on every Root, PoseBone, Leg controller, and Upper-limb controller keyframe_insert() call so any False return aborts frame commit with frame, target identity, and data_path before updating Tracker or Bridge state.
                # REASON: TASK 12-B BUG-05
                # Keyframe root object
                if root is not None:
                    for data_path in ("location", "rotation_euler"):
                        if not root.keyframe_insert(data_path, frame=frame):
                            raise RuntimeError(
                                f"Failed to insert keyframe for object {root.name!r}.{data_path} at frame {frame}"
                            )

                # Keyframe armature pose bones
                for pb in arm.pose.bones:
                    for data_path in ("location", "rotation_euler"):
                        if not pb.keyframe_insert(data_path, frame=frame):
                            raise RuntimeError(
                                f"Failed to insert keyframe for pose bone {arm.name!r}.{pb.name}.{data_path} at frame {frame}"
                            )

                # [INTRODUCED 2026-11-26T17:52:00+08:00]
                # TASK: TASK 10-d-4
                # BLOCK: Phase 6 leg & upper-limb controller rotation-mode-preserving keyframing + arm constraint influence keyframing
                # PURPOSE: Preserve rotation_mode on HandIK/ElbowPole empties when inserting location/rotation keyframes, and record true post-solve ArmIK/HandRotation constraint influences with CONSTANT FCurve interpolation via Blender 5.1.1 Action Slot/Channelbag.
                # REASON: Resolve P02 (missing ArmIK/HandRotation influence persistence and controller rotation channel mismatch) without changing legacy Root/bone/leg controller contracts, fabricating weights, mutating rotation modes, or altering unrelated FCurves.
                for name in ("FootIK.L", "FootIK.R", "KneePole.L", "KneePole.R"):
                    obj = bpy.data.objects.get(name)
                    if obj is not None:
                        for data_path in ("location", "rotation_euler"):
                            if not obj.keyframe_insert(data_path, frame=frame):
                                raise RuntimeError(
                                    f"Failed to insert keyframe for controller {obj.name!r}.{data_path} at frame {frame}"
                                )

                for name in ("HandIK.L", "HandIK.R", "ElbowPole.L", "ElbowPole.R"):
                    obj = bpy.data.objects.get(name)
                    if obj is not None:
                        rot_mode = str(obj.rotation_mode)
                        if rot_mode == "QUATERNION":
                            rot_path = "rotation_quaternion"
                        elif rot_mode == "AXIS_ANGLE":
                            rot_path = "rotation_axis_angle"
                        elif rot_mode in ("XYZ", "XZY", "YXZ", "YZX", "ZXY", "ZYX"):
                            rot_path = "rotation_euler"
                        else:
                            raise ValueError(
                                f"Unsupported rotation_mode {rot_mode!r} on upper-limb controller {name!r} at frame {frame}"
                            )
                        for data_path in ("location", rot_path):
                            if not obj.keyframe_insert(data_path, frame=frame):
                                raise RuntimeError(
                                    f"Failed to insert keyframe for controller {obj.name!r}.{data_path} at frame {frame}"
                                )

                expected_influence_paths = set()
                for side in ("L", "R"):
                    for bone_name, con_name in (
                        (f"forearm.{side}", ARM_IK_CONSTRAINT_NAMES[side]),
                        (f"hand.{side}", HAND_ROT_CONSTRAINT_NAMES[side]),
                    ):
                        pbone = arm.pose.bones.get(bone_name)
                        if pbone is None:
                            raise RuntimeError(
                                f"Missing required pose bone {bone_name!r} on {arm.name!r} for Phase 6 influence keyframing"
                            )
                        con = pbone.constraints.get(con_name)
                        if con is None:
                            raise RuntimeError(
                                f"Missing required constraint {con_name!r} on {bone_name!r} for Phase 6 influence keyframing"
                            )
                        _ = float(con.influence)
                        if not con.keyframe_insert("influence", frame=frame):
                            raise RuntimeError(
                                f"Failed to insert influence keyframe for {bone_name!r}/{con_name!r} at frame {frame}"
                            )
                        expected_influence_paths.add(con.path_from_id("influence"))

                adt = arm.animation_data
                action = adt.action if adt is not None else None
                if action is None:
                    raise RuntimeError(
                        f"Armature {arm.name!r} has no Action after Phase 6 constraint influence keyframing"
                    )
                fcurve_groups = []
                slot = getattr(adt, "action_slot", None)
                if hasattr(action, "layers"):
                    if slot is None:
                        raise RuntimeError(
                            f"Armature {arm.name!r} Action {action.name!r} has no assigned action_slot"
                        )
                    for layer in action.layers:
                        for strip in layer.strips:
                            cb = strip.channelbag(slot)
                            if cb is not None:
                                fcurve_groups.append(cb.fcurves)
                elif hasattr(action, "fcurves"):
                    fcurve_groups.append(action.fcurves)

                matched_paths = set()
                for fcurves in fcurve_groups:
                    for fc in fcurves:
                        if fc.data_path not in expected_influence_paths:
                            continue
                        key_found = False
                        for kp in fc.keyframe_points:
                            if abs(float(kp.co[0]) - float(frame)) < 1e-4:
                                kp.interpolation = "CONSTANT"
                                key_found = True
                        if key_found:
                            matched_paths.add(fc.data_path)

                if matched_paths != expected_influence_paths:
                    missing_paths = sorted(expected_influence_paths - matched_paths)
                    raise RuntimeError(
                        f"Failed to locate Phase 6 influence FCurves/keyframes on {arm.name!r} at frame {frame}: {missing_paths}"
                    )

            # Publish precomputed causal kinematics and cross-frame state after successful solve & keyframing
