"""Minimal Compatibility Bridge Layer (Task 6G-C-R3B-1).

Physics-constraint-assisted procedural animation: unifies historical MotionAction
kinematic generation with the WholeBodyController pose coordinator and the single-frame
6-phase execution protocol.

Architectural Principles Enforced:
1. MotionAction generates kinematic targets and contact intent (Phase 1).
2. Contact coordination layer preserves established stance foot anchors in world space
   via `foot_contact.py` (Phase 2).
3. WholeBodyController holds exclusive write ownership of Blender Armature pose bones
   and IK controller Empty objects, dispatching FK and IK solvers (Phase 3).
4. Truthful validation: JointModel ROM checking and reachability evaluation. If ROM
   clamping creates end-effector reach conflicts, failure is truthfully reported (Phase 4).
5. Read-only physics telemetry: CoM, kinematics, inertia, and contact model are evaluated
   post-pose and never act as unverified direct force actuators (Phase 5).
6. State commit: packaged into an immutable `MotionState` snapshot (Phase 6).
"""

